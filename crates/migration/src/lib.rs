//! Schema migrations. Append-only: never edit a migration that has shipped,
//! add a new one instead.
//!
//! The server applies all pending migrations in ONE transaction (holding a
//! transaction-scoped advisory lock, see `oauth_server::db::migrate`), so a
//! migration must be transaction-safe: no `CREATE INDEX CONCURRENTLY`, no
//! `ALTER TYPE … ADD VALUE` followed by use of the new value in the same run.
//!
//! Conventions:
//! - Enumerations are `text` + `CHECK (col IN (…))`, not Postgres enum types:
//!   extending a CHECK is a plain drop/add inside the migration transaction,
//!   whereas a new enum value can't be used in the transaction that adds it
//!   and enum values can never be removed.
//! - Primary keys are UUIDv7 generated by the application (Postgres 17 has no
//!   `uuidv7()`); time-ordered keys keep B-tree inserts local.
//! - Every tenant-scoped table carries `tenant_id`; children reference parents
//!   via `(tenant_id, id)` so cross-tenant links are impossible.

